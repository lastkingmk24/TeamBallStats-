/* =========================================================================
 * pro.js — PRO analytics (PURE). Served by the backend only to accounts
 * with an active Pro entitlement (see server/app.js). The same code runs in
 * Node on the server, so the rules are identical everywhere.
 *
 *   lineupRankings(state, opts)  five-man lineups ranked by net points per
 *                                10 minutes while on court, from substitution
 *                                events and the play-by-play
 *   gameRecap(state, gameId)     game recap: a MEASURED section (box score
 *                                numbers) and an ANALYSIS section (rule-based
 *                                statements that quote those numbers). The
 *                                analysis is generated by fixed rules; it is
 *                                not a language-model output.
 * ========================================================================= */
(function (TBS) {
  'use strict';

  const an = TBS.analytics;
  const st = TBS.stats;
  const num = v => (Number.isFinite(Number(v)) ? Number(v) : 0);

  /* Seconds a team's five-man unit was on court, with points for / against
   * during each stint. Returns null when the side has no substitution data. */
  function stints(game, league, teamId) {
    const events = (game.events || []).filter(Boolean);
    const oppId = teamId === game.homeTeamId ? game.awayTeamId : game.homeTeamId;
    const firstSub = {};
    events.forEach(e => {
      if (e.teamId === teamId && (e.type === 'sub_in' || e.type === 'sub_out') && firstSub[e.playerId] === undefined) {
        firstSub[e.playerId] = e.type;
      }
    });
    if (!Object.keys(firstSub).length) return null;

    /* Starters: first sub was a sub_out, or they played before any sub_in. */
    const on = {};
    Object.keys(firstSub).forEach(pid => { if (firstSub[pid] === 'sub_out') on[pid] = true; });
    const subbedIn = {};
    events.forEach(e => {
      if (e.teamId !== teamId || !e.playerId) return;
      if (e.type === 'sub_in') { subbedIn[e.playerId] = true; return; }
      if (e.type === 'sub_out' || !e.statDeltas || !Object.keys(e.statDeltas).length) return;
      if (firstSub[e.playerId] === 'sub_in' && !subbedIn[e.playerId]) on[e.playerId] = true;
    });

    const out = [];
    let current = { ids: Object.keys(on).sort(), start: 0, pf: 0, pa: 0 };
    const close = (at) => {
      out.push({ ids: current.ids, seconds: Math.max(0, at - current.start), pf: current.pf, pa: current.pa });
    };
    events.forEach(e => {
      const at = an.elapsedSeconds(league, e.quarter, e.clockSeconds);
      if (e.teamId === teamId && (e.type === 'sub_in' || e.type === 'sub_out') && e.playerId) {
        close(at);
        const set = current.ids.filter(id => id !== e.playerId);
        if (e.type === 'sub_in') set.push(e.playerId);
        current = { ids: set.sort(), start: at, pf: 0, pa: 0 };
        return;
      }
      const delta = num(e.scoreDelta);
      if (!delta) return;
      if (e.teamId === teamId) current.pf += delta;
      else if (e.teamId === oppId) current.pa += delta;
    });
    close(an.gameLengthSeconds(league, game));
    return out;
  }

  /* opts: { minMinutes: 3, size: 5, games: 'final' | 'all', teamId? } */
  function lineupRankings(state, opts) {
    const o = opts || {};
    const minSeconds = num(o.minMinutes === undefined ? 3 : o.minMinutes) * 60;
    const size = o.size === undefined ? 5 : num(o.size);
    const league = state.league || {};
    const players = state.players || [];
    const pool = (state.games || []).filter(g => o.games === 'all' ? true : g.status === 'final');
    const games = o.teamId
      ? pool.filter(g => g.homeTeamId === o.teamId || g.awayTeamId === o.teamId)
      : pool;
    const byKey = {};
    let gamesTracked = 0;

    games.forEach(game => {
      [game.homeTeamId, game.awayTeamId].forEach(teamId => {
        if (o.teamId && teamId !== o.teamId) return;
        const list = stints(game, league, teamId);
        if (!list) return;
        gamesTracked++;
        list.forEach(s => {
          if (s.seconds <= 0 || s.ids.length !== size) return;
          const key = teamId + '|' + s.ids.join(',');
          const row = byKey[key] || (byKey[key] = {
            key: key, teamId: teamId, playerIds: s.ids, names: s.ids.map(id => {
              const p = players.find(x => x.id === id);
              return p ? '#' + p.number + ' ' + p.name : 'Former player';
            }),
            games: {}, seconds: 0, pf: 0, pa: 0
          });
          row.games[game.id] = true;
          row.seconds += s.seconds;
          row.pf += s.pf;
          row.pa += s.pa;
        });
      });
    });

    const rows = Object.keys(byKey).map(k => {
      const r = byKey[k];
      const net = r.pf - r.pa;
      return {
        key: r.key, teamId: r.teamId, playerIds: r.playerIds, names: r.names,
        gp: Object.keys(r.games).length,
        minutes: Math.round(r.seconds / 6) / 10,
        pf: r.pf, pa: r.pa, net: net,
        netPer10: r.seconds > 0 ? Math.round((net / (r.seconds / 600)) * 10) / 10 : 0,
        qualified: r.seconds >= minSeconds
      };
    });
    rows.sort((a, b) => Number(b.qualified) - Number(a.qualified) ||
      b.netPer10 - a.netPer10 || b.minutes - a.minutes);
    let rank = 0;
    rows.forEach(r => { if (r.qualified) r.rank = ++rank; else r.rank = null; });

    return {
      tracked: gamesTracked > 0,
      gamesTracked: gamesTracked,
      minMinutes: minSeconds / 60,
      size: size,
      rankings: rows.filter(r => r.qualified),
      all: rows,
      note: gamesTracked
        ? 'Lineups come from substitution events. A stint runs from one substitution to the next; ' +
          'points are the scoring recorded while that five was on the floor.'
        : 'No substitution data yet. Record subs in the Live Console (on-court toggles) to rank lineups.'
    };
  }

  /* Impact index for a player line: a simple, transparent box-score measure. */
  function impact(s) {
    return num(s.pts) + num(s.reb) + num(s.ast) + num(s.stl) + num(s.blk) - num(s.tov) -
      (num(s.fga) - num(s.fgm)) - (num(s.fta) - num(s.ftm));
  }

  /* Largest unanswered scoring run by either team, from the play-by-play. */
  function largestRun(game) {
    let best = { team: null, points: 0 };
    let run = { team: null, points: 0 };
    (game.events || []).forEach(e => {
      const d = num(e.scoreDelta);
      if (d <= 0) return;
      if (run.team === e.teamId) run.points += d;
      else run = { team: e.teamId, points: d };
      if (run.points > best.points) best = { team: run.team, points: run.points };
    });
    return best;
  }

  function leadChanges(game) {
    let margin = 0;
    let lead = 0;
    let changes = 0;
    (game.events || []).forEach(e => {
      const d = num(e.scoreDelta);
      if (!d) return;
      margin += e.teamId === game.homeTeamId ? d : (e.teamId === game.awayTeamId ? -d : 0);
      const sign = margin > 0 ? 1 : (margin < 0 ? -1 : 0);
      if (sign !== 0) {
        if (lead !== 0 && sign !== lead) changes++;
        lead = sign;
      }
    });
    return changes;
  }

  /* Game recap for one game. Throws a plain Error when the game is unknown. */
  function gameRecap(state, gameId) {
    const league = state.league || {};
    const game = (state.games || []).find(g => g.id === gameId);
    if (!game) throw new Error('Game not found');
    const players = state.players || [];
    const teams = state.teams || [];
    const box = st.gameBox(game, players, teams, league);
    const H = box.home;
    const A = box.away;
    const h = H.totals;
    const a = A.totals;
    const pctOf = (m, t) => (num(t) > 0 ? Math.round((num(m) / num(t)) * 1000) / 10 : null);
    const margin = game.homeScore - game.awayScore;

    /* MEASURED: numbers straight from the box score and play-by-play. */
    const measured = {
      score: { home: num(game.homeScore), away: num(game.awayScore), homeName: H.team.name, awayName: A.team.name },
      status: game.status,
      margin: Math.abs(margin),
      winner: margin === 0 ? null : (margin > 0 ? H.team.name : A.team.name),
      quarters: st.quarterScores(game, league),
      teams: {
        home: { name: H.team.name, fg: pctOf(h.fgm, h.fga), fgm: h.fgm, fga: h.fga, tpm: h.tpm, tpa: h.tpa,
          tp: pctOf(h.tpm, h.tpa), ftm: h.ftm, fta: h.fta, ft: pctOf(h.ftm, h.fta),
          reb: h.reb, oreb: h.oreb, dreb: h.dreb, ast: h.ast, tov: h.tov, pf: h.pf, stl: h.stl, blk: h.blk },
        away: { name: A.team.name, fg: pctOf(a.fgm, a.fga), fgm: a.fgm, fga: a.fga, tpm: a.tpm, tpa: a.tpa,
          tp: pctOf(a.tpm, a.tpa), ftm: a.ftm, fta: a.fta, ft: pctOf(a.ftm, a.fta),
          reb: a.reb, oreb: a.oreb, dreb: a.dreb, ast: a.ast, tov: a.tov, pf: a.pf, stl: a.stl, blk: a.blk }
      },
      largestRun: (function () {
        const r = largestRun(game);
        return { team: r.team === game.homeTeamId ? H.team.name : (r.team === game.awayTeamId ? A.team.name : null),
          points: r.points };
      })(),
      leadChanges: leadChanges(game),
      topPerformers: H.rows.concat(A.rows)
        .map(r => ({ name: r.player.name, number: r.player.number,
          team: r.player.teamId === game.homeTeamId ? H.team.name : A.team.name,
          pts: r.stats.pts, reb: r.stats.reb, ast: r.stats.ast, stl: r.stats.stl, blk: r.stats.blk,
          tov: r.stats.tov, fgm: r.stats.fgm, fga: r.stats.fga, pf: r.stats.pf,
          impact: impact(r.stats) }))
        .sort((x, y) => y.impact - x.impact || y.pts - x.pts)
        .slice(0, 3)
    };

    /* ANALYSIS: fixed rules over the measured numbers. Each item says which
     * numbers it used so the reader can check it. */
    const analysis = [];
    const add = (text, basis) => analysis.push({ text: text, basis: basis });
    if (game.status === 'final' && margin !== 0) {
      if (Math.abs(margin) <= 3) {
        add(measured.winner + ' won a one-possession game by ' + Math.abs(margin) + '.', 'final score');
      } else if (Math.abs(margin) >= 20) {
        add('A ' + Math.abs(margin) + '-point margin: the game was decided early and held.', 'final score');
      }
    }
    if (measured.largestRun.points >= 8 && measured.largestRun.team) {
      add(measured.largestRun.team + ' scored ' + measured.largestRun.points + ' unanswered points, the largest run of the game.',
        'largest unanswered run from the play-by-play');
    }
    if (measured.leadChanges >= 3) {
      add('The lead changed hands ' + measured.leadChanges + ' times, so the game was competitive throughout.', 'lead changes from the running margin');
    }
    const tovGap = h.tov - a.tov;
    if (Math.abs(tovGap) >= 3) {
      const careless = tovGap > 0 ? H.team.name : A.team.name;
      add(careless + ' committed ' + Math.abs(tovGap) + ' more turnovers (' + h.tov + ' vs ' + a.tov +
        '), which gave the other side extra possessions.', 'turnovers ' + h.tov + ' vs ' + a.tov);
    }
    const rebGap = h.reb - a.reb;
    if (Math.abs(rebGap) >= 5) {
      const winner = rebGap > 0 ? H.team.name : A.team.name;
      const split = (h.oreb || a.oreb) ? '; offensive ' + h.oreb + ' vs ' + a.oreb : '';
      add(winner + ' won the rebounding battle by ' + Math.abs(rebGap) + ' (' + h.reb + ' vs ' + a.reb + split + ').',
        'rebounds ' + h.reb + ' vs ' + a.reb);
    }
    const fgH = pctOf(h.fgm, h.fga);
    const fgA = pctOf(a.fgm, a.fga);
    if (fgH !== null && fgA !== null && Math.abs(fgH - fgA) >= 8) {
      const better = fgH > fgA ? H.team.name : A.team.name;
      add(better + ' shot ' + Math.max(fgH, fgA) + '% from the field against ' + Math.min(fgH, fgA) + '%.',
        'FG% ' + fgH + ' vs ' + fgA);
    }
    const ftGap = h.fta - a.fta;
    if (Math.abs(ftGap) >= 6) {
      const more = ftGap > 0 ? H.team.name : A.team.name;
      add(more + ' got to the line ' + Math.abs(ftGap) + ' more times (' + h.fta + ' vs ' + a.fta + ' attempts).',
        'free-throw attempts ' + h.fta + ' vs ' + a.fta);
    }
    const q = measured.quarters;
    if (q.tracked && q.tracked.some(Boolean)) {
      let worst = null;
      q.home.forEach((hv, i) => {
        if (!q.tracked[i]) return;
        const diff = hv - q.away[i];
        if (!worst || Math.abs(diff) > Math.abs(worst.diff)) worst = { i: i, diff: diff };
      });
      if (worst && Math.abs(worst.diff) >= 8) {
        const team = worst.diff > 0 ? H.team.name : A.team.name;
        add('Quarter ' + (worst.i + 1) + ' belonged to ' + team + ' by ' + Math.abs(worst.diff) + '.',
          'quarter scores ' + q.home[worst.i] + '–' + q.away[worst.i]);
      }
    }
    const fouled = H.rows.concat(A.rows).filter(r => r.stats.pf >= 4);
    fouled.forEach(r => {
      add(r.player.name + ' finished with ' + r.stats.pf + ' fouls, a foul-trouble risk for the rotation.',
        'personal fouls ' + r.stats.pf);
    });
    if (measured.topPerformers[0]) {
      const t = measured.topPerformers[0];
      add(t.name + ' had the highest impact index (' + t.impact + '): ' + t.pts + ' pts, ' + t.reb + ' reb, ' +
        t.ast + ' ast, ' + t.stl + ' stl, ' + t.blk + ' blk, ' + t.tov + ' tov.',
        'impact = PTS+REB+AST+STL+BLK−TOV−missed FG−missed FT');
    }
    if (!analysis.length) {
      add('Nothing stood out under the fixed rules: the game was balanced across the measured categories.', 'no rule threshold reached');
    }

    return {
      gameId: game.id,
      date: game.date,
      measured: measured,
      analysis: analysis,
      labels: {
        measured: 'Measured — counted from the box score and play-by-play.',
        analysis: 'Analysis — generated by fixed rules from the measured numbers above. It is not a language-model summary.'
      }
    };
  }

  TBS.pro = {
    lineupRankings: lineupRankings,
    gameRecap: gameRecap,
    stints: stints,
    impact: impact
  };
})(window.TBS = window.TBS || {});
